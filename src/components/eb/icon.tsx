export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 20,
  strokeWidth = 1.6,
  ...props
}: { name: IconName | (string & {}); size?: number } & Omit<LucideProps, "size">) {
  const Component = (ICONS as Record<string, typeof Sun>)[name];
  if (!Component) return <span style={{ width: size, height: size }} aria-hidden />;
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden {...props} />;
}

